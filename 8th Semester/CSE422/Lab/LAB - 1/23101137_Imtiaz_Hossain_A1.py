d= int(d)  # ---^

# print(c)
# print(d)

maze = []

for i in range(n):
    temp = input.readline().rstrip("\n") # '###0####'
    temp = list(temp)                    # ['#', '#', '#', '0', '#', '#', '#', '#']
    maze.append(temp)

#print(maze)

entry_point = [a, b]   # (0, 3) --> ['#', '#', '#', '0', '#', '#', '#', '#']
exit_point = [c, d]    # (6, 5) --> ['#', '#', '#', '#', '#', '0', '#', '#']

#print(entry_point)
#print(exit_point)

total_path_cost = 0

import heapq

def maze_solver(maze, entry_point, exit_point):

    if entry_point[0] < n and entry_point[0] > -1 and entry_point[1] < m and entry_point[1] > -1:         # ---> Checking validility of entry_point
        if exit_point[0] < n and exit_point[0] > -1 and exit_point[1] <= m and exit_point[1] > -1:        # ---> Checking validility of exit_point
            if maze[entry_point[0]][entry_point[1]] == '0' and maze[exit_point[0]][exit_point[1]] == "0": # ---> Checking enter_point/exit_point if it is blocked or not
                if entry_point[0] == exit_point[0] and entry_point[1] == exit_point[1]:                   # ---> To check if it's the exit point or not.
                    output.write(str(total_path_cost) + "\n")
                    return

                else:

                    def manhattan_distance(x, y):                    # ---> Manhattan distance (x, y) = |x1 - x2| + |y1- y2|
                        return abs(x[0] - y[0]) + abs(x[1] - y[1])

                    possible_moves = [(-1, 0, "U"), (1, 0, "D"), (0, 1, "R"), (0, -1, "L")]

                    seen_idx = set()
                    priority_queue = []

                    # initital cost = 0

                    heapq.heappush(priority_queue, (manhattan_distance(entry_point, exit_point), 0, tuple(entry_point), ""))   # ---> initital cost, cost_so_far = 0
                                                                                                                               # ---> Manhattan distance = |0 - 6| + |3 - 5| = 8

                    # f = total_estimated_cost -> 4
                    # g = cost_so_far          -> 0
                    # (x, y) = position        -> (0, 3)
                    # path = directions taken  -> ""

                    while priority_queue:
                        f, g, (x, y), path = heapq.heappop(priority_queue)

                        if (x, y) == tuple(exit_point):
                            output.write(str(g) + "\n")
                            output.write(path)
                            return

                        if (x, y) in seen_idx:
                            continue

                        seen_idx.add((x, y))

                        for i, j, k in possible_moves:
                            new_x = x + i
                            new_y = y + j

                            if new_x < n and new_x > -1 and new_y < m and new_y > -1:
                                if maze[new_x][new_y] == "0":
                                    if (new_x, new_y) not in seen_idx:
                                        new_h = manhattan_distance((new_x, new_y), exit_point)
                                        new_g = g + 1

                                        new_f = new_g + new_h # Total

                                        heapq.heappush(priority_queue, (new_f, new_g, (new_x, new_y), path + k))  # Adding next step to the queue


                    output.write("-1")     # ---> print("While No Path Found")
            else:
                output.write("-1")         # ---> print("Entry/Exit Point is Blocked")
        else:
            output.write("-1")             # ---> print("Invalid Exit Point")
    else:
        output.write("-1")                 # ---> print("Invalid Entry Point")



maze_solver(maze, entry_point, exit_point)

