############################<---Create Graph-->#################################

def create_graph(edges):
    G = {}

    for u, v in edges:
        if u not in G:
            G[u] = []
        if v not in G:
            G[v] = []

        G[u].append(v)
        G[v].append(u)

    return G

G= create_graph(edges)
#print(G)

#################################<---BFS--->####################################

from collections import deque

def bfs(G, goal):
    Q= deque()
    distance = {}

    for u in G:
        distance[u] = float('inf')

    distance[goal] = 0
    Q.append(goal)

    while Q:
        u = Q.popleft()

        for i in G[u]:
            if distance[i] == float('inf'):
                distance[i] = distance[u] + 1
                Q.append(i)

        #print(u)

    return distance

